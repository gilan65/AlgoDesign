// Il codice atteso delle tabelle (i vettori di record), scritto a mano prima dei generatori (un atteso ricavato dal
// generatore darebbe ragione al generatore): `tipi/copia-di-una-tabella` intero nei tre linguaggi e nelle due lingue,
// `tipi/tabella-come-parametro` intero in italiano nel Python e nel C, col programma di prova della funzione che
// restituisce una tabella, e la provenienza delle righe delle copie. La tabella è una lista di oggetti della classe di dati
// nel Python (ognuno dal suo costruttore, la copia record per record col costruttore) e un vettore di `struct` nel C; la
// copia col nome è il ciclo dei record con una riga per campo, e un record della tabella si copia campo per campo.
