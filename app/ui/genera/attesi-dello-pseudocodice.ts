// dicono a mano quanti spazi vanno prima del commento.
import type { Progetto } from "../../core/progetto/modello";

const sp = (n: number) => " ".repeat(n);
const testo = (...righe: string[]) => righe.join("\n") + "\n";

export interface Atteso {
  readonly it: string;
  readonly en: string;
}

