// «Accademico» atteso, scritto a mano dalla sintassi prima del generatore (un atteso ricavato dal generatore darebbe
// ragione al generatore): i cinque esempi forniti che ci stanno, un file del corpus per ogni costrutto che si traduce, e
// un programma scritto qui con ciò che i file del corpus che ci stanno non hanno (il ripeti, anche annidato, la costante,
// la costante comune semplice, il booleano come parametro e come risultato, la condizione restituita, i `per ogni`
// annidati, le parentesi di `mod`, di `and` dentro `or` e del meno). Le parole chiave sono le stesse in ogni lingua: le
// due forme differiscono solo nei nomi che il testo aggiunge (`_indice`, `_sorgente`, `_ancora`).
//
// In più, l'esito atteso di ogni file del corpus: il codice, gli errori statici (che vengono prima di ciò che manca),
// o le mancanze, contate a parte dal secondo rilevatore della prova.
