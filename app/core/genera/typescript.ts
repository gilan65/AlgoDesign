/** Gli a capo di una riga di testo: quelli di una fine riga, e i due separatori di Unicode che in JavaScript chiudono un
 * commento `//`. */
const aCapo = new RegExp(`\\r\\n|[\\r\\n${String.fromCharCode(0x2028, 0x2029)}]`);

const albero = (testo: string): Espressione => {
  const a = analizza(testo);
  // Il controllo statico ha già provato sintassi e tipi: qui non ci sono errori.
  if (!a.ok) throw new Error(`espressione non analizzabile dopo il controllo: ${testo}`);
  return a.espressione;
};

// ------------------------------------------------------------------------------------- la guardia

/** Gli operatori del primo gruppo di costrutti. */
const operatoriDelloScheletro = new Set(["+", "-", "*", "/", "mod", "<", "<=", ">", ">=", "==", "!=", "and", "or", "not"]);

/** Il primo costrutto di un'espressione che il generatore non sa ancora scrivere; `scrittura`, se è un valore intero di
 * una scrittura (dove un letterale stringa ci sta). */
function nonAncoraNellEspressione(e: Espressione, scrittura = false): string | undefined {
  switch (e.genere) {
    case "intero":
    case "booleano":
    case "nome":
      return undefined;
    case "stringa":
      return scrittura ? undefined : "il letterale stringa fuori da una scrittura";
    case "reale":
      return "il letterale reale";
    case "pi":
      return "pi greco";
    case "carattere":
      return "il letterale carattere";
    case "indice":
      return "l'indice";
    case "campo":
      return "il campo di un record";
    case "chiamata":
      return "la chiamata di una funzione";
    case "unario":
      return operatoriDelloScheletro.has(e.operatore) ? nonAncoraNellEspressione(e.operando) : `l'operatore ${e.operatore}`;
    case "binario":
      return operatoriDelloScheletro.has(e.operatore) ? (nonAncoraNellEspressione(e.sinistro) ?? nonAncoraNellEspressione(e.destro)) : `l'operatore ${e.operatore}`;
  }
}

const nomeDelBlocco: Readonly<Record<Blocco["kind"], string | undefined>> = {
  assignment: undefined,
  write: undefined,
  comment: undefined,
  read: "la lettura",
  if: "il se",
  while: "il mentre",
  repeat: "il ripeti",
  for: "il per",
  for_each: "il per ogni",
  call: "la chiamata di una procedura",
};

/** Il primo costrutto del progetto che il generatore non sa ancora scrivere, o niente. */
function nonAncora(p: Progetto, prova: Prova | undefined): string | undefined {
  if (prova !== undefined) return "il programma di prova di una procedura o di una funzione";
  if (p.functions.length > 1) return "le procedure e le funzioni";
  if ((p.records ?? []).length > 0) return "il record";
  const main = p.functions[0]!;
  for (const d of [...(p.shared_constants ?? []), ...main.data]) {
    if (d.type === "record") return d.size === undefined ? "il record" : "la tabella";
    if (d.columns !== undefined) return "la matrice";
    if (d.size !== undefined) return "il vettore";
    if (d.type !== "integer" && d.type !== "boolean") return { real: "il tipo reale", character: "il tipo carattere", string: "il tipo stringa" }[d.type];
    if (d.initial !== undefined) {
      const nelValore = nonAncoraNellEspressione(albero(d.initial as string));
      if (nelValore !== undefined) return nelValore;
    }
  }
  for (const b of main.body) {
    const blocco = nomeDelBlocco[b.kind];
    if (blocco !== undefined) return blocco;
    if (b.kind === "assignment") {
      const t = albero(b.target);
      if (t.genere !== "nome") return nonAncoraNellEspressione(t) ?? "l'assegnazione a una parte di un dato";
      const v = nonAncoraNellEspressione(albero(b.value));
      if (v !== undefined) return v;
    }
    if (b.kind === "write")
      for (const v of b.values) {
        const e = albero(v);
        const nelValore = nonAncoraNellEspressione(e, e.genere === "stringa");
        if (nelValore !== undefined) return nelValore;
      }
  }
  return undefined;
}

// ------------------------------------------------------------------------------------------- il programma

function righeDelTypeScript(p: Progetto, lingua: LinguaDelCodice, note: NoteDeiDati): Riga[] {
  const w = testi[lingua];
  const nomi: Readonly<Record<Supporto, string>> = {
    dividi: nomiDelSupporto[lingua].dividi,
    booleano: nomiDelSupporto[lingua].booleano,
    scrivi: nomiDelSupportoDelTypeScript[lingua].scrivi,
  };
  const main = p.functions.find((f) => f.kind === "main")!;
  const comuni = p.shared_constants ?? [];
  const dati = new Map<string, Dato>([...comuni, ...main.data].map((d) => [d.name, d]));

  const usate = new Set<Supporto>();
  const usa = (f: Supporto): string => {
    usate.add(f);
    return nomi[f];
  };

  // ------------------------------------------------------------------------------------------- i tipi

  function tipo(e: Espressione): TipoDelDato {
    switch (e.genere) {
      case "intero":
        return "integer";
      case "booleano":
        return "boolean";
      case "stringa":
        return "string";
      case "nome":
        return dati.get(e.nome)!.type;
      case "unario":
        return e.operatore === "not" ? "boolean" : "integer";
      case "binario":
        return e.operatore === "+" || e.operatore === "-" || e.operatore === "*" || e.operatore === "/" || e.operatore === "mod" ? "integer" : "boolean";
      default:
        throw new Error(`espressione fuori dal primo gruppo di costrutti: ${e.genere}`);
    }
  }

  // ------------------------------------------------------------------------------------- le espressioni

  /** Il testo di TypeScript e la forza con cui tiene il suo operatore (più alta, più stretta), come le precedenze di
   * JavaScript: 20 un operando o una chiamata; 15 il meno e `!`; 12 `*` e `%`; 11 `+` e `-`; 10 i confronti d'ordine;
   * 9 `===` e `!==`; 5 `&&`; 4 `||`. */
  type Testo = { readonly t: string; readonly forza: number };
  const operando = (t: string): Testo => ({ t, forza: 20 });
  const fra = (x: Testo, forza: number) => (x.forza < forza ? `(${x.t})` : x.t);
  const operatori: Readonly<Record<string, readonly [string, number]>> = {
    "+": ["+", 11],
    "-": ["-", 11],
    "*": ["*", 12],
    mod: ["%", 12],
    "<": ["<", 10],
    "<=": ["<=", 10],
    ">": [">", 10],
    ">=": [">=", 10],
    "==": ["===", 9],
    "!=": ["!==", 9],
    and: ["&&", 5],
    or: ["||", 4],
  };

  /** Un lato che `tsc` può vedere col tipo letterale: un letterale intero (col meno davanti) o booleano, un dato booleano
   * (un intero non si restringe mai). */
  const letteraleOBooleano = (e: Espressione): boolean =>
    e.genere === "intero" || e.genere === "booleano" || (e.genere === "unario" && e.operatore === "-" && e.operando.genere === "intero") || (e.genere === "nome" && tipo(e) === "boolean");

  function espressione(e: Espressione): Testo {
    switch (e.genere) {
      case "intero":
        return operando(String(e.valore));
      case "booleano":
        return operando(e.valore ? "true" : "false");
      case "nome":
        return operando(e.nome);
      case "unario": {
        const x = espressione(e.operando);
        if (e.operatore === "not") return { t: `!${fra(x, 15)}`, forza: 15 };
        // Un meno davanti a un meno: `--` sarebbe il decremento.
        return { t: x.t.startsWith("-") ? `-(${x.t})` : `-${fra(x, 15)}`, forza: 15 };
      }
      case "binario": {
        const l = espressione(e.sinistro);
        const r = espressione(e.destro);
        if (e.operatore === "/") return operando(`${usa("dividi")}(${l.t}, ${r.t})`);
        const [op, forza] = operatori[e.operatore]!;
        // Un confronto dentro un confronto va fra parentesi da tutti e due i lati.
        const confronto = forza === 9 || forza === 10;
        // `tsc` rifiuta l'uguaglianza fra due tipi letterali diversi (TS2367): due letterali, o un booleano che un
        // letterale assegnato prima restringe a `true` o `false`. Il lato sinistro allarga il suo tipo con `as`.
        const sinistro = forza === 9 && letteraleOBooleano(e.sinistro) && letteraleOBooleano(e.destro) ? operando(`(${l.t} as ${tipo(e.sinistro) === "boolean" ? "boolean" : "number"})`) : l;
        return { t: `${fra(sinistro, confronto ? 11 : forza)} ${op} ${fra(r, confronto ? 11 : forza + 1)}`, forza };
      }
      default:
        throw new Error(`espressione fuori dal primo gruppo di costrutti: ${e.genere}`);
    }
  }

  /** Un codice in un testo composto: i caratteri che il testo composto legge a modo suo, e quelli di controllo. */
  function nelTesto(codice: number): string {
    const c = String.fromCodePoint(codice);
    if (c === "`" || c === "\\" || c === "$") return `\\${c}`;
    if (c === "\n") return "\\n";
    if (c === "\t") return "\\t";
    if (c === "\r") return "\\r";
    if (codice < 0x20 || codice === 0x7f) return `\\x${codice.toString(16).padStart(2, "0")}`;
    return c;
  }

  /** Un valore di una scrittura dentro il testo composto. */
  function nellaScrittura(v: string): string {
    const e = albero(v);
    if (e.genere === "stringa") return e.codici.map(nelTesto).join("");
    const x = espressione(e).t;
    return tipo(e) === "boolean" ? `\${${usa("booleano")}(${x})}` : `\${${x}}`;
  }

  // ---------------------------------------------------------------------------------------- le dichiarazioni

  const annotazione = (d: Dato) => (d.type === "boolean" ? "boolean" : "number");

  /** Le dichiarazioni, con la colonna dei commenti allineata sulle righe che ne hanno uno. */
  const dichiara = (elenco: readonly Dato[], prima: string, conNota: boolean): Riga[] => {
    const voci = elenco.map((d) => {
      const v = d.initial === undefined ? undefined : espressione(albero(d.initial as string)).t;
      const parola = d.constant === true || prima === "" ? "const" : "let";
      const nota = !conNota ? "" : d.constant === true ? note.costante : d.role !== undefined ? note.ruoli[d.role] : "";
      return { d, testo: `${prima}${parola} ${d.name}${v === undefined ? "!" : ""}: ${annotazione(d)}${v === undefined ? "" : ` = ${v}`};`, nota };
    });
    const larghezza = (t: string) => Array.from(t).length;
    const colonna = Math.max(0, ...voci.filter((x) => x.nota !== "").map((x) => larghezza(x.testo)));
    return voci.map(({ d, testo, nota }) => ({ testo: nota === "" ? testo : `${testo}${" ".repeat(colonna - larghezza(testo))}  // ${nota}`, dato: d.name }));
  };

  // --------------------------------------------------------------------------------------------- le regole

  const corpo: Riga[] = [];
  function blocco(b: Blocco) {
    const riga = (testo: string) => corpo.push({ testo: rientro + testo, blocco: b.id });
    switch (b.kind) {
      case "assignment":
        return riga(`${(albero(b.target) as { nome: string }).nome} = ${espressione(albero(b.value)).t};`);
      case "write":
        return riga(`${usa("scrivi")}(\`${b.values.map(nellaScrittura).join("")}${b.newline ? "\\n" : ""}\`);`);
      case "comment":
        for (const t of b.text.split(aCapo)) riga(t === "" ? "//" : `// ${t}`);
        return;
      default:
        throw new Error(`blocco fuori dal primo gruppo di costrutti: ${b.kind}`);
    }
  }

  const dichiarazioni = dichiara(main.data, rientro, true);
  for (const b of main.body) blocco(b);
  const principale = segnate([{ testo: "function main(): void {" }, ...dichiarazioni, ...corpo, { testo: "}" }], main.id);
  const costanti = dichiara(comuni, "", false);

  // --------------------------------------------------------------------------------------- l'insieme

  const nome = p.metadata.name.split(aCapo).join(" ");
  const righe: Riga[] = [
    { testo: `// ${nome}` },
    { testo: `// ${w.generato}` },
    ...w.nonControllati.map((t) => ({ testo: `// ${t}` })),
    ...(usate.has("scrivi") ? [{ testo: 'import { writeSync } from "node:fs";' }] : []),
  ];
  if (costanti.length > 0) righe.push({ testo: "" }, { testo: `// ${w.costantiComuni}` }, ...costanti);
  righe.push({ testo: "" }, { testo: "" }, ...principale);
  const funzioni = supportoInOrdine.filter((f) => usate.has(f));
  if (funzioni.length > 0) {
    righe.push({ testo: "" }, { testo: "" }, { testo: `// ${w.supporto}` });
    funzioni.forEach((f, i) => righe.push(...(i === 0 ? [{ testo: "" }, { testo: "" }] : [{ testo: "" }, { testo: "" }]), ...funzione(f, lingua, nomi).map((testo) => ({ testo }))));
  }
  righe.push({ testo: "" }, { testo: "" }, { testo: "main();" });
  return righe;
}

// -------------------------------------------------------------------------------- le funzioni di supporto

/** Il testo di una funzione di supporto: la spiegazione, la firma, il corpo. */
function funzione(f: Supporto, lingua: LinguaDelCodice, nomi: Readonly<Record<Supporto, string>>): string[] {
  const s = `/** ${spiegazioni[lingua][f]} */`;
  switch (f) {
    case "dividi":
      return [s, `function ${nomi.dividi}(a: number, b: number): number {`, "  return Math.trunc(a / b);", "}"];
    case "booleano":
      return [s, `function ${nomi.booleano}(b: boolean): string {`, '  return b ? "true" : "false";', "}"];
    case "scrivi": {
      const t = testi[lingua].testo;
      return [s, `function ${nomi.scrivi}(${t}: string): void {`, `  writeSync(1, ${t});`, "}"];
    }
  }
}
