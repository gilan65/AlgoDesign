// Il TypeScript di un progetto: un programma che sui casi d'uso dà lo stesso output dell'interprete, eseguito da Node.js
// (o da Bun) così com'è, nella lingua dell'interfaccia (i nomi delle funzioni di supporto, i commenti). La semantica resta
// quella del C, come nel Python: gli interi sono `number` e la divisione fra interi passa da `dividi`, che tronca verso lo
// zero; il resto è `%`, che in JavaScript ha già il segno del dividendo come nel C. I comportamenti che il C non definisce
// non si controllano, e il commento in testa lo dice. Solo sintassi che si cancella togliendo i tipi (niente `enum` né
// `namespace`): il programma resta JavaScript a meno delle annotazioni.
//
// Il generatore cresce un gruppo di costrutti per volta. Oggi sa scrivere il programma principale coi dati e le costanti
// interi e booleani (senza vettori), l'assegnazione a un dato, la scrittura (coi letterali stringa), il commento e le
// espressioni intere e booleane; per ogni altro costrutto il progetto non si genera, e `nonAncora` dice il primo che
// trova («la lettura», «il tipo reale», «il se»…), dopo gli errori statici come un generatore che si ferma.
//
// La forma: il nome del progetto e la testa, l'import da `node:fs` della sola funzione che scrive (isolata nella funzione
// di supporto `scrivi`, che una pagina nel browser può sostituire), le costanti comuni, `main` coi dati annotati dalla
// vista dei dati (`let`, o `const` per una costante; un dato senza valore iniziale `let x!: number;`, perché `tsc` non lo
// dica usato prima di avere un valore in un programma valido; il ruolo o «costante» in una colonna allineata di
// commenti), le regole, poi le sole funzioni di supporto che il programma usa, in un ordine fisso, e la chiamata di
// `main`. Una scrittura è un testo composto (`` scrivi(`${q} ${r}\n`) ``): un intero com'è, un booleano da `booleano`, un
// letterale stringa dentro il testo coi caratteri che il testo composto protegge (`` ` ``, `\`, `$`, i caratteri di
// controllo).
//
// Le espressioni si riscrivono dall'albero, non dal testo, con le precedenze di JavaScript (un confronto dentro un
// confronto sta fra parentesi da tutti e due i lati, come nel Python, anche dove JavaScript non le vorrebbe; un meno
// davanti a un meno sta fra parentesi, perché `--` è un altro operatore). Un `===` o `!==` fra due letterali, o fra un
// dato booleano e un letterale o un altro booleano, allarga il tipo del lato sinistro (`(p as boolean) === false`):
// `tsc` rifiuta l'uguaglianza fra due tipi letterali diversi, e un booleano assegnato con un letterale ne ha uno.
//
// La provenienza delle righe è quella del Python: la riga di un blocco ha quel blocco, la dichiarazione di un dato ha il
// dato, le righe di struttura (`function main(): void {`, la graffa, la testa) e le funzioni di supporto nessuna; le
// righe di `main` sono segnate come sue.
//
// Che cosa NON fa: controllare un intero oltre i 32 bit, la divisione per zero, il dato senza valore (i calcoli che il C
// non definisce).

import type { Tetti } from "../controllo/controllo";
import { analizza, type Espressione } from "../espressioni/analizzatore";
import type { Blocco, Dato, Progetto, TipoDelDato } from "../progetto/modello";
import { genera, segnate, type Generato, type Riga } from "./forma";
import { nomiDelSupporto, nomiDelSupportoDelTypeScript, type LinguaDelCodice } from "./nomi";
import type { NoteDeiDati, Prova } from "./python";

export function typescript(p: Progetto, limiti: Tetti, lingua: LinguaDelCodice, note: NoteDeiDati, prova?: Prova): Generato {
  return genera(p, limiti, (q) => righeDelTypeScript(q, lingua, note), undefined, (q) => nonAncora(q, prova));
}

